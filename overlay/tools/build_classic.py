"""Build a local Classic application and package it without the installed codec.

Uses the native upstream build and variant. Never opens a radio or publishes.
"""
from pathlib import Path
import argparse
import hashlib
import json
import os
import subprocess
import tomllib
import zipfile
import boards

ROOT = Path(__file__).resolve().parents[1]
VERSION = "open25-classic-0.1.0-rc1-r15-dev"
PROFILE = {
    "PRODUCT_CLASSIC": "y", "CPS_RFKV_ONLY": "y",
    "FM": "y", "DMR": "y", "P25": "y", "NXDN": "y", "HRC7000_NATIVE_RX": "y", "P25_MIC_AGC": "y",
    "HOSTLINK": "y", "DEBUGLINK": "y", "CPS_OPENFW": "y", "CPS_FAST": "y", "STUB_ENTRY": "y",
}


def classic_profile(board=None):
    candidates = sorted(p.parent.name for p in (ROOT / "boards").glob("*/classic.toml"))
    if board is None:
        if len(candidates) != 1:
            raise ValueError("Select --board from: " + ", ".join(candidates))
        board = candidates[0]
    if board not in candidates:
        raise ValueError("No Classic product profile for this board")
    owner = boards.load(root=str(ROOT), only=[board])[board]
    values = tomllib.loads((ROOT / "boards" / board / "classic.toml").read_text())
    base = owner.platform.data["flash_base"]
    if not owner.codec_slot or owner.app_region[1] > owner.codec_slot[0]:
        raise ValueError("Classic needs an application region below its installed codec slot")
    return {**values, "board": board, "app_base": owner.app_base - base,
            "app_end": owner.app_region[1] - base}


def product_header(directory, profile=None):
    profile = profile or classic_profile()
    path = Path(directory) / "classic_product.h"
    path.parent.mkdir(parents=True, exist_ok=True)
    text = ('// SPDX-License-Identifier: MIT\n'
            '// Generated by tools/build_classic.py; product identity only.\n'
            '#define BUILD_PRODUCT_NAME ' + json.dumps(profile["name"]) + '\n'
            '#define BUILD_PRODUCT_MAINTAINER ' + json.dumps(profile["maintainer"]) + '\n')
    if not path.exists() or path.read_text() != text:
        path.write_text(text)
    return path


def package_application(application, destination, version=VERSION, newlib_notice=None, profile=None):
    profile = profile or classic_profile()
    data = Path(application).read_bytes()
    app_base, app_end = profile["app_base"], profile["app_end"]
    if not data or len(data) > app_end - app_base:
        raise ValueError("Application must fit entirely below the existing codec slot")
    if not version.startswith("open25-classic-"):
        raise ValueError("Classic package needs its own product version")
    manifest = {"format": profile["format"], "version": 2, "target": profile["target"],
                "release": version, "applicationSha256": hashlib.sha256(data).hexdigest(),
                "codecTablesEnd": profile["codec_tables_end"],
                "programming": {"schema": "rfkv-p25-contact-v1"}}
    destination = Path(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    entries = {"firmware.json": (json.dumps(manifest, indent=2) + "\n").encode(), "application.bin": data}
    notices = ["LICENSE", "AUTHORS", "CONTRIBUTORS", "platform/hrc7000/THIRD_PARTY", "core/mbe/THIRD_PARTY",
               "third_party/FreeRTOS-Kernel/LICENSE.md"]
    notices += [str(p.relative_to(ROOT)) for p in sorted((ROOT / "LICENSES").glob("*.txt"))]
    for name in notices:
        p = ROOT / name
        if not p.is_file():
            raise ValueError("Missing required license/attribution: " + name)
        entries["notices/" + name] = p.read_bytes()
    # Keep the original font copyright and permission headers, rather than relying on a generic license template.
    # They are refreshed from the compiled upstream font sources every time a package is produced.
    for name in ("spleen_5x8.inc", "jbmono_6x12.inc"):
        source = (ROOT / "core/ui/fonts" / name).read_text()
        entries["notices/fonts/" + name + ".txt"] = source.split("#define", 1)[0].encode()
    if newlib_notice is not None:
        entries["notices/LICENSES/newlib-COPYING.NEWLIB.txt"] = Path(newlib_notice).read_bytes()
    with zipfile.ZipFile(destination, "w", zipfile.ZIP_STORED) as archive:
        for name, content in entries.items():
            item = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            item.compress_type = zipfile.ZIP_STORED
            item.external_attr = 0o100644 << 16
            archive.writestr(item, content)
    with zipfile.ZipFile(destination) as archive:
        assert archive.read("application.bin") == data
        assert json.loads(archive.read("firmware.json")) == manifest
        assert set(archive.namelist()) == set(entries)
    return {"path": str(destination), "sha256": hashlib.sha256(destination.read_bytes()).hexdigest(),
            "application_bytes": len(data), "application_sha256": manifest["applicationSha256"],
            "application_range": [app_base, app_base + len(data)], "codec_range_written": False,
            "newlib_notice_included": newlib_notice is not None,
            "entries": sorted(entries)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--board", help="Board with a Classic product profile (auto-selected when unique)")
    parser.add_argument("--cross", default="csky-elf-", help="Existing C-SKY compiler prefix")
    parser.add_argument("--jobs", type=int, default=8)
    parser.add_argument("--stack-check", action="store_true")
    parser.add_argument("--verify-rebuild", action="store_true")
    parser.add_argument("--build-only", action="store_true")
    parser.add_argument("--package-only", action="store_true", help="Refresh the existing application package without compiling")
    parser.add_argument("--newlib-notice", type=Path, help="Existing COPYING.NEWLIB for the linked local toolchain")
    parser.add_argument("--print-command", action="store_true")
    args = parser.parse_args()
    profile = classic_profile(args.board)
    out = ROOT / "build/classic-test"
    if args.package_only:
        receipt = json.loads((out / "build-manifest.json").read_text())
        receipt["package"] = package_application(out / ("rfoundry_" + profile["board"] + ".bin"), out / (VERSION + "-application.zip"),
                                                  newlib_notice=args.newlib_notice, profile=profile)
        (out / "build-manifest.json").write_text(json.dumps(receipt, indent=2) + "\n")
        print(json.dumps(receipt["package"], indent=2))
        return
    header = product_header(out / "gen", profile)
    epoch = subprocess.check_output(["git", "show", "-s", "--format=%ct", "HEAD"], cwd=ROOT, text=True).strip()
    command = ["make", "BOARD=" + profile["board"], "VARIANT=classic", "BUILD=build/classic-test", "CROSS=" + args.cross,
               "RFOUNDRY_VERSION=" + VERSION, "RFOUNDRY_GIT_TIME=" + epoch, "RFOUNDRY_GIT_DIRTY=1",
               "OPT=-Os -include " + str(header), *["CONFIG_" + k + "=" + v for k, v in PROFILE.items()],
               "-j" + str(args.jobs)]
    if args.print_command:
        print(json.dumps(command))
        return
    logs = out / "logs"
    logs.mkdir(parents=True, exist_ok=True)
    env = {**os.environ, "SOURCE_DATE_EPOCH": epoch}
    def run(extra, log):
        with (logs / log).open("w") as f:
            subprocess.run([*command, *extra], cwd=ROOT, env=env, stdout=f, stderr=subprocess.STDOUT, check=True)
        if "warning:" in (logs / log).read_text():
            raise RuntimeError("Compiler warning; inspect " + str(logs / log))
    run([], "build.log")
    application = out / ("rfoundry_" + profile["board"] + ".bin")
    original = application.read_bytes()
    if args.stack_check:
        run(["stack-check"], "stack.log")
    if args.verify_rebuild:
        run(["-B"], "rebuild.log")
        if application.read_bytes() != original:
            raise RuntimeError("Forced rebuild changed application bytes")
    receipt = {"version": VERSION, "unreleased": True, "source_commit": subprocess.check_output(
        ["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip(), "command": command,
        "application_sha256": hashlib.sha256(original).hexdigest(), "application_bytes": len(original),
        "stack_check": args.stack_check, "identical_forced_rebuild": args.verify_rebuild}
    if not args.build_only:
        receipt["package"] = package_application(application, out / (VERSION + "-application.zip"),
                                                   newlib_notice=args.newlib_notice, profile=profile)
    (out / "build-manifest.json").write_text(json.dumps(receipt, indent=2) + "\n")
    print(json.dumps(receipt, indent=2))


if __name__ == "__main__":
    main()
