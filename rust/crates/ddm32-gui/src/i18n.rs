/// The text of key in lang ("tr" or "en"); the key itself when unknown (visible, and caught by a test).
pub fn t(lang: &str, key: &str) -> String {
    match TEXTS.iter().find(|(k, _, _)| *k == key) {
        Some((_, tr, en)) => (if lang == "en" { *en } else { *tr }).to_string(),
        None => key.to_string(),
    }
}

/// t() with its "{}" replaced.
pub fn tf(lang: &str, key: &str, arg: &str) -> String {
    t(lang, key).replacen("{}", arg, 1)
}
